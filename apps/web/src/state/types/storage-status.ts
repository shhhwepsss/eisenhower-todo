/**
 * Состояние связи с хранилищем (docs/specs/4-architecture.md §5).
 *
 * Четыре значения, и последние два — разные беды с разным ответом экрана:
 *
 * - `loading` — снапшот ещё не прочитан, в хранилище нельзя писать ничего
 *   (порт асинхронный, §4, а бэкенд позже будет читать снапшот так же
 *   асинхронно).
 * - `ready` — снапшот прочитан, запись разрешена.
 * - `unavailable` — снапшот не прочитан: хранилище недоступно либо его
 *   содержимое повреждено (CORRUPTED_SNAPSHOT_IS_PRESERVED — оба случая сюда,
 *   потому что до конца сессии писать нельзя в обоих). Задач в состоянии ещё
 *   нет, поэтому терять нечего — экран блокирует работу целиком.
 * - `write-failed` — снапшот был прочитан, но запись отказала (квота,
 *   приватный режим). Задачи уже в состоянии и на экране, и прятать их
 *   отказом чтения было бы потерей — работа продолжается, персист выключен.
 *
 * Что именно пошло не так, знает `StorageError` в логе; экрану нужен только флаг.
 */
export type StorageStatus = 'loading' | 'ready' | 'unavailable' | 'write-failed';
