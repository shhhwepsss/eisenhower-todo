import styles from './AppStorageError.module.scss';

/**
 * Экран отказа хранилища вместо вкладок — по аналогии с `AppLoader` при
 * `'loading'` (см. JSDoc там же). Решение владельца продукта: запасного
 * хранилища в памяти больше нет, поэтому недоступный или повреждённый
 * `localStorage` — это не повод молча работать с задачами, которые негде
 * сохранить. Вкладки и создание задач в этом состоянии не монтируются вовсе,
 * а не прячутся за баннером поверх работающего интерфейса — STORAGE_FAILURE_IS_VISIBLE
 * (docs/specs/4-architecture.md §3).
 */
export const AppStorageError = () => {
  return (
    <p className={styles.error} role="alert">
      Хранилище недоступно или его содержимое повреждено. Работать с задачами нельзя —
      обновите страницу или проверьте настройки браузера.
    </p>
  );
};
