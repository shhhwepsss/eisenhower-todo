/**
 * Версия формата снапшота (docs/specs/4-architecture.md §3).
 *
 * Миграций в MVP нет: версия одна, мигрировать не с чего. Само поле при этом
 * обязательно и откладыванию не подлежит — снапшоты v1 пишутся уже сейчас, и если
 * их не проштамповать, отличить потом «старый формат» от «новый формат, старая
 * запись» будет нечем.
 *
 * Следствие, названное заранее: когда появится v2, снапшоты v1 читаться перестанут,
 * пока вместе с v2 не приедет миграция. Отказ громкий и наступает сразу — в отличие
 * от чтения v1 «как получится», которое и есть та потеря данных, от которой поле
 * версии защищает.
 */
