/**
 * Чем именно хранилище не смогло помочь (docs/specs/4-architecture.md §3).
 *
 * Разные виды требуют разного разговора с пользователем: «данные повреждены»
 * предлагает начать заново, «версия из будущего» — обновить вкладку, «квота»
 * — освободить место. Один `boolean` этого различия не несёт, а разбор строки
 * сообщения — это парсинг собственного текста.
 */
export type StorageErrorKind =
  /** Снапшот не разбирается: JSON не парсится либо форма не та. */
  | 'unreadable'
  /** Версия снапшота не та, которую понимает этот код (SCHEMA_VERSION_IS_EXPLICIT). */
  | 'unsupported-version'
  /** Запись не удалась: квота, приватный режим, отказ браузера. */
  | 'write-failed'
  /** Хранилища нет вовсе: обращение к нему бросает. */
  | 'unavailable';
