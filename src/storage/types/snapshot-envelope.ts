/**
 * Содержимое конверта снапшота: JSON разобран, версия сошлась — а что лежит
 * внутри, ещё неизвестно.
 *
 * Отдельный тип, а не голый `Record<string, unknown>` по месту: он отмечает
 * ровно ту точку разбора, где проверка версии уже прошла, а проверка формы
 * (SNAPSHOT_SHAPE_IS_CHECKED) ещё нет.
 */
export type SnapshotEnvelope = Record<string, unknown>;
