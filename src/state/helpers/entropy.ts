/**
 * Всё недетерминированное собрано здесь — REDUCER_IS_PURE (спека §5).
 *
 * Редьюсер получает `id` и время готовыми в payload, а вызываются эти две функции
 * ровно в одном месте, в `useTaskActions`. Тогда «редьюсер не читает часы» —
 * не договорённость, а свойство кода: часов в нём попросту нет.
 */

/** UUID v4: ID_IS_GLOBALLY_UNIQUE (PRD §7 — идентификатор не должен зависеть от устройства). */
export const createId = (): string => crypto.randomUUID();

/** ISO-8601 UTC — единственная форма времени в модели (спека §2). */
export const now = (): string => new Date().toISOString();
