/**
 * Состояние связи с хранилищем (docs/specs/4-architecture.md §5).
 *
 * Три значения: `loading` — снапшот ещё не прочитан, в хранилище нельзя писать
 * ничего (порт асинхронный, §4, а бэкенд позже будет читать снапшот так же
 * асинхронно); `ready` — снапшот прочитан, запись разрешена; `error` —
 * прочитать или записать не удалось, данные пользователя в опасности. Что
 * именно пошло не так, знает `StorageError` в логе; экрану нужен только флаг.
 */
export type StorageStatus = 'loading' | 'ready' | 'error';
