import styles from './AppLoader.module.scss';

/**
 * Загрузчик на время чтения снапшота: порт асинхронный (docs/specs §4),
 * а бэкенд, который придёт позже, будет отвечать так же не мгновенно.
 *
 * Появление отложено чистым CSS (`animation-delay`), а не JS-таймером:
 * задержка нужна ровно затем, чтобы быстрое чтение из localStorage не успело
 * мигнуть загрузчиком на экране, а CSS решает это без лишнего состояния
 * компонента и без риска забыть отменить таймер при размонтировании.
 * Экран-ридер при этом не ждёт: `role="status"` и `aria-busy` стоят на
 * элементе с первого кадра, отложена только его видимость.
 */
export const AppLoader = () => {
  return (
    <p className={styles.loader} role="status" aria-busy="true">
      Загружаем задачи…
    </p>
  );
};
